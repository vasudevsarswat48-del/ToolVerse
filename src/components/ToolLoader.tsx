const cache = new Map<string, React.LazyExoticComponent<ComponentType>>();

function getLazy(slug: string) {
  let c = cache.get(slug);
  if (!c) {
    const loader = LOADERS[slug];
    if (!loader) return null;
    c = lazy(loader);
    cache.set(slug, c);
  }
  return c;
}

export default function ToolLoader({ slug }: { slug: string }) {
  const LazyComp = useMemo(() => getLazy(slug), [slug]);
  if (!LazyComp) {
    return <div style={{ textAlign: "center", padding: "3rem", color: "var(--muted)" }}>Tool not found.</div>;
  }
  return (
    <Suspense
      fallback={
        <div style={{ textAlign: "center", padding: "3rem", color: "var(--muted)", fontSize: 14 }}>
          Loading…
        </div>
      }
    >
      <LazyComp />
    </Suspense>
  );
}
